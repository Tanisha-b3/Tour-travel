export function lookupCoords(destination) {
  if (!destination) return null;
  if (typeof destination.lat === "number" && typeof destination.lng === "number" && (destination.lat || destination.lng)) {
    return { lat: destination.lat, lng: destination.lng };
  }
  const haystack = [destination.location, destination.region, destination.name]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
  for (const key of Object.keys(CITY_COORDS)) {
    if (haystack.includes(key)) return CITY_COORDS[key];
  }
  const tokens = haystack.split(/[\s,]+/).filter((t) => t.length > 3);
  for (const token of tokens) {
    for (const key of Object.keys(CITY_COORDS)) {
      if (token.includes(key) || key.includes(token)) return CITY_COORDS[key];
    }
  }
  return null;
}

